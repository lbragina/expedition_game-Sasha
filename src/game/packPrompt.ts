// ТЗ для Claude Code на новую пачку стран. Это служебный текст для мамы (копируется в буфер обмена),
// а не интерфейс игры для Саши — поэтому он написан по-русски. Список уже добавленных стран подставляется автоматически.
import { COUNTRIES } from '../data/countries'

export function buildPackPrompt(count = 12): string {
  const existing = COUNTRIES.map((c) => `- ${c.id} ${c.emoji} (lon: ${c.lon}, lat: ${c.lat})`).join('\n')
  const ids = COUNTRIES.map((c) => c.id).join(', ')
  return `Привет! Нужна Пачка стран для обучающей PWA-игры «L'Expédition» (папка проекта открыта). Игрок — Саша, 12 лет, 6e, Люксембург. Все тексты на естественном французском. Node.js лежит в .tools/node/bin (export PATH="$PWD/.tools/node/bin:$PATH").

Добавь ${count} НОВЫХ стран (по 2 экспедиции на страну). Уже добавленные страны (id) — НЕ дублируй:
${existing}

Список id: ${ids}

Выбери страны, которых нет в списке выше. Для каждой новой страны создай по единому шаблону (логику игры — actions.ts, selection.ts, MapTab.tsx — менять НЕ нужно: она сама подхватывает всё по COUNTRIES, fr.json и префиксам вопросов):

1. src/data/countries.ts — добавь в конец массива COUNTRIES: { id: '<id>', emoji: '<эмодзи>', lon: <долгота>, lat: <широта> } (id латиницей, строчными, без пробелов; координаты точные).
2. src/i18n/fr.json → countries.<id>: { "name": "...", "fact": "...", "log": "..." }.
   - fact: 2–3 точных проверяемых факта с числами/названиями.
   - log: запись капитана от первого лица (Sasha со скейтом и стройкой базы), содержит конкретные детали, по которым можно задать вопрос.
3. src/data/questions/world.json — ровно 3 вопроса на страну (category "world", stars 0, ladder [], hints — 3 подсказки, image null, lang "fr"):
   - riddle-<id> (topic "enigme", difficulty 2, type "choice"): загадка-анонс «Quel pays suis-je ?» по фактам страны, НЕ называя страну; 4 варианта, дистракторы не должны тоже подходить под описание.
   - diary-<id> (topic "journal", difficulty 3): вопрос строго по факту из fact.
   - diary2-<id> (topic "journal", difficulty 3): вопрос строго по детали из log.
   - Для type "choice" — ровно 4 options и answer = индекс 0–3; для "number" — answer числом.
4. ПРАВИЛО ПЕРЕМЕШИВАНИЯ: во всех вопросах type "choice" правильный ответ должен быть равномерно распределён по индексам 0, 1, 2, 3 (не все на 0!). После перемешивания проверь, что answer указывает на правильный вариант.

Дополнительно:
- Подставь страны на карту аккуратно: если страна рядом с другими (например, в Европе), убедись, что маркеры читаемы (в MapTab есть переключатель «Europe»).
- Факты должны быть точными; если не уверена в числе — используй более осторожную формулировку.
- Сохраняй формат JSON (отступ 2 пробела, без правки существующих вопросов).

Проверки (всё должно пройти без ошибок): npm run validate, npm run verify-math, npm run check-i18n, npm run build. Затем закоммить изменения и выполни git push origin main.`
}
